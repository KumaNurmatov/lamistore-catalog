def main():
    specs = json.loads((ROOT / "data" / "eparket_specs.json").read_text(encoding="utf-8"))
    # Официальные сайты перекрывают магазин: там, где товара на eparket нет,
    # и там, где данные производителя точнее.
    for name in ("official_specs.json", "manual_specs.json"):
        f = ROOT / "data" / name
        if f.exists():
            specs.update(json.loads(f.read_text(encoding="utf-8")))

    tabs, empty = {}, []
    for article, rec in specs.items():
        sp = rec["specs"]
        rows = [(label, sp[key]) for key, label in ORDER if key in sp and sp[key] not in ("", "—")]
        if not rows:
            empty.append(article); continue
        body = "<br />".join(f"{k}: {v}" for k, v in rows)
        tabs[article] = {"kind": "info", "title": "Подробная информация",
                         "body": body, "source": rec["url"]}
        print(f"  {article:<14}{len(rows):>3} строк   {rec['url'][:58]}")

    out = ROOT / "data" / "product_tabs.json"
    out.write_text(json.dumps(tabs, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\nШторок собрано: {len(tabs)}" + (f"   пусто: {empty}" if empty else ""))
    print(f"-> {out}")

if __name__ == "__main__":
    main()
